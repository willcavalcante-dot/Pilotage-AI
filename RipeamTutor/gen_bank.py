#!/usr/bin/env python3
"""Compile questions.json into bank.rs for the glasses (id, question, reference
answer, citation) and check each question fits the question screen."""
from pathlib import Path
import json, sys
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'tools'))
from gen_bank import wrap, check_text, lit, blob, F24  # same glyph tables/wrap as the glasses

def main():
    data = json.loads((HERE / 'questions.json').read_text(encoding='utf-8'))
    recs, ids = [], set()
    for q in data['questions']:
        if q['id'] in ids or not q['id'].isascii() or len(q['id']) > 15: raise SystemExit('bad id ' + q['id'])
        ids.add(q['id'])
        f = [q['id'].encode(), str(q['level']).encode(), q['q'].encode(), q['a'].encode(), q['ref'].encode()]
        for x in f: check_text(q['id'], x)
        if len(wrap(f[2], F24, 592)) > 10: raise SystemExit(q['id'] + ': question longer than 10 lines')
        if len(f[3]) > 1400: raise SystemExit(q['id'] + ': answer too long for the result message')
        recs.append(f)
    b, o = blob(recs)
    (HERE / 'bank.rs').write_text(f"""// GENERATED by RipeamTutor/gen_bank.py from questions.json - do not edit.
// Records: id, level, question, reference answer, citation (NUL-separated).
pub const VERSION: &str = {json.dumps(data['version'])};
pub const N: usize = {len(recs)};
pub static BLOB: &[u8] = {lit(b)};
pub static OFF: [u16; {len(o)}] = {o};
""", encoding='utf-8')
    print(f"{len(recs)} questions, {len(b)} bytes")

if __name__ == '__main__':
    main()
